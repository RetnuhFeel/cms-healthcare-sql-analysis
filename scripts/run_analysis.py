#!/usr/bin/env python3
"""
Run every analysis query in sql/05_analysis/ and save the output.

For each qNN_*.sql file this writes:
  results/qNN_*.csv   - the full result set
and one combined results/RESULTS.md with every result as a Markdown table,
so reviewers can read the numbers on GitHub without running anything.

Uses only psql (libpq environment variables: PGHOST, PGPORT, PGUSER, PGDATABASE ...)
and the Python standard library. Exits non-zero if any query fails or returns no rows.
"""
from __future__ import annotations

import csv
import io
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SQL_DIR = ROOT / "sql" / "05_analysis"
OUT_DIR = ROOT / "results"


def run_query(path: Path) -> list[list[str]]:
    proc = subprocess.run(
        ["psql", "-X", "-q", "--csv", "-v", "ON_ERROR_STOP=1", "-f", str(path)],
        capture_output=True, text=True,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"{path.name} failed:\n{proc.stderr}")
    return list(csv.reader(io.StringIO(proc.stdout)))


def question_text(path: Path) -> str:
    """First comment line(s) of the file, e.g. '-- Q01. Which ...'."""
    lines = []
    for line in path.read_text().splitlines():
        if not line.startswith("--"):
            break
        text = line[2:].strip()
        if text.lower().startswith(("skills:", "business ask:", "note:")):
            break
        lines.append(text)
    return " ".join(lines)


def to_markdown(rows: list[list[str]]) -> str:
    header, body = rows[0], rows[1:]
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(cell.replace("|", "\\|") for cell in r) + " |" for r in body]
    return "\n".join(out)


def main() -> int:
    OUT_DIR.mkdir(exist_ok=True)
    files = sorted(SQL_DIR.glob("q*.sql"))
    md = ["# Query results", "",
          "Generated by `scripts/run_analysis.py` from the committed sample data. Do not edit by hand.", ""]
    failures = 0
    for path in files:
        try:
            rows = run_query(path)
        except RuntimeError as exc:
            print(exc, file=sys.stderr)
            failures += 1
            continue
        if len(rows) < 2:
            print(f"{path.name}: returned no rows", file=sys.stderr)
            failures += 1
            continue
        with open(OUT_DIR / f"{path.stem}.csv", "w", newline="") as fh:
            csv.writer(fh).writerows(rows)
        print(f"ok  {path.name:45s} {len(rows) - 1:4d} rows")
        md += [f"## {question_text(path)}", "",
               f"Query: [`{path.relative_to(ROOT)}`](../{path.relative_to(ROOT)})", "",
               to_markdown(rows), ""]
    (OUT_DIR / "RESULTS.md").write_text("\n".join(md))
    print(f"{len(files) - failures}/{len(files)} queries succeeded")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
